import { describe, expect, it } from 'vitest'
import {
  parseEdl,
  parseEdlTime,
  serializeEdl,
  edlToSkipIntervals,
  findActiveEdlCut,
  EDL_ACTION_CUT,
  EDL_ACTION_COMMERCIAL,
  EDL_ACTION_MUTE,
  type EdlEntry,
} from './edlParser'

describe('EDL Commercial & Cut Parser', () => {
  it('parses timestamps across seconds and timecode formats', () => {
    expect(parseEdlTime('120')).toBe(120)
    expect(parseEdlTime('120.55')).toBe(120.55)
    expect(parseEdlTime('01:30')).toBe(90)
    expect(parseEdlTime('01:00:00')).toBe(3600)
    expect(parseEdlTime('00:02:15.500')).toBe(135.5)
    expect(parseEdlTime('')).toBe(0)
    expect(parseEdlTime('invalid')).toBe(0)
  })

  it('parses standard EDL content with comments, whitespace, and action codes', () => {
    const rawEdl = `
      # Comskip Commercial Break File
      ; Generated by MythTV / Comskip
      60.000 120.000 0 Commercial Break 1
      300.500 360.500 3 Sponsor Break
      500.000 520.000 1 Audio Mute Region
    `

    const entries = parseEdl(rawEdl)
    expect(entries.length).toBe(3)

    expect(entries[0]).toEqual({
      startSec: 60,
      endSec: 120,
      action: EDL_ACTION_CUT,
      label: 'Commercial Break 1',
    })

    expect(entries[1]).toEqual({
      startSec: 300.5,
      endSec: 360.5,
      action: EDL_ACTION_COMMERCIAL,
      label: 'Sponsor Break',
    })

    expect(entries[2]).toEqual({
      startSec: 500,
      endSec: 520,
      action: EDL_ACTION_MUTE,
      label: 'Audio Mute Region',
    })
  })

  it('ignores invalid lines where endSec <= startSec', () => {
    const raw = `
      100 50 0 Invalid backwards cut
      200 200 0 Zero length cut
      300 350 3 Valid cut
    `
    const entries = parseEdl(raw)
    expect(entries.length).toBe(1)
    expect(entries[0]?.startSec).toBe(300)
    expect(entries[0]?.endSec).toBe(350)
  })

  it('serializes and round-trips EDL entries', () => {
    const initial: EdlEntry[] = [
      { startSec: 45.5, endSec: 90.25, action: 0, label: 'Ad 1' },
      { startSec: 210, endSec: 270, action: 3 },
    ]

    const text = serializeEdl(initial)
    const reparsed = parseEdl(text)

    expect(reparsed.length).toBe(2)
    expect(reparsed[0]?.startSec).toBe(45.5)
    expect(reparsed[0]?.endSec).toBe(90.25)
    expect(reparsed[0]?.label).toBe('Ad 1')
  })

  it('converts EDL cuts into Kinora SkipInterval objects', () => {
    const entries: EdlEntry[] = [
      { startSec: 60, endSec: 120, action: 0, label: 'Intro Cut' },
      { startSec: 200, endSec: 220, action: 1, label: 'Mute Region' }, // Should be excluded from skip intervals
      { startSec: 400, endSec: 460, action: 3, label: 'Station Promo' },
    ]

    const intervals = edlToSkipIntervals(entries)
    expect(intervals.length).toBe(2)
    expect(intervals[0]?.type).toBe('commercial')
    expect(intervals[0]?.startSec).toBe(60)
    expect(intervals[0]?.endSec).toBe(120)
    expect(intervals[1]?.type).toBe('commercial')
    expect(intervals[1]?.startSec).toBe(400)
  })

  it('finds active EDL cuts during playback position evaluation', () => {
    const entries: EdlEntry[] = [
      { startSec: 100, endSec: 150, action: 0 },
      { startSec: 300, endSec: 360, action: 3 },
    ]

    // Before cut
    expect(findActiveEdlCut(50, entries)).toBeNull()

    // Inside cut 1
    const cut1 = findActiveEdlCut(120, entries)
    expect(cut1).toBeTruthy()
    expect(cut1?.startSec).toBe(100)
    expect(cut1?.endSec).toBe(150)

    // Between cuts
    expect(findActiveEdlCut(200, entries)).toBeNull()

    // Inside cut 2
    const cut2 = findActiveEdlCut(359.9, entries)
    expect(cut2).toBeTruthy()
    expect(cut2?.startSec).toBe(300)

    // After cut 2
    expect(findActiveEdlCut(360, entries)).toBeNull()
  })
})
