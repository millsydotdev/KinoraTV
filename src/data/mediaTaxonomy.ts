export function getCategory(id: string): MediaCategoryDefinition | undefined {
  return MEDIA_TAXONOMY.find((c) => c.id === id)
}

export function getAllSubcategories(): { categoryId: string; subcategory: MediaSubcategory }[] {
  return MEDIA_TAXONOMY.flatMap((c) => c.subcategories.map((sub) => ({ categoryId: c.id, subcategory: sub })))
}
