// Generator for series episodes
function buildSeriesEpisodes(
  seriesId: string,
  seasonNum: number,
  titlesAndSynopses: Array<[string, string, number]>,
  baseStill = '',
): Episode[] {
  return titlesAndSynopses.map(([title, synopsis, runtime], index) => {
    const number = index + 1
    return {
      id: `s${seasonNum}e${number}`,
      seriesId,
      season: seasonNum,
      number,
      title,
      synopsis,
      runtime,
      still: baseStill,
      stillFocus: 50,
    }
  })
}

