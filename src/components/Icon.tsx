export type IconName = keyof typeof tablerIcons

export function Icon({
  name,
  size = 20,
  className,
  style,
  fill,
  stroke = 1.8,
}: {
  name: IconName
  size?: number
  className?: string
  style?: CSSProperties
  fill?: string
  stroke?: number
}) {
  const Component = tablerIcons[name] ?? IconHome
  return (
    <Component
      size={size}
      stroke={stroke}
      className={className}
      style={style}
      fill={fill ?? (name === 'play' ? 'currentColor' : 'none')}
      aria-hidden="true"
    />
  )
}
