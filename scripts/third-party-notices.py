#!/usr/bin/env python3
"""Writes public/THIRD-PARTY-NOTICES.txt from what actually ships: production npm packages and the Rust
crates linked for Linux, with each package's own licence text. --check fails if the file is out of date."""
import json, os, re, subprocess, sys
ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
OUT = os.path.join(ROOT, 'public', 'THIRD-PARTY-NOTICES.txt')
LICENCE_FILE = re.compile(r'^(licen[cs]e|copying|notice|unlicense|ofl)([-._].*)?(\.(md|txt|rst))?$', re.I)

def texts(folder):
    out = []
    for name in sorted(os.listdir(folder)):
        path = os.path.join(folder, name)
        if LICENCE_FILE.match(name) and os.path.isfile(path):
            with open(path, encoding='utf-8', errors='replace') as f:
                out.append((name, f.read().strip()))
    return out

def npm_packages():
    lock = json.load(open(os.path.join(ROOT, 'package-lock.json'), encoding='utf-8'))['packages']
    for key, p in lock.items():
        if key and not p.get('dev') and not p.get('optional'):
            yield key.split('node_modules/')[-1], p['version'], p.get('license', 'UNKNOWN'), os.path.join(ROOT, key)

def cargo_packages():
    meta = json.loads(subprocess.check_output(
        ['cargo', 'metadata', '--format-version', '1', '--locked', '--filter-platform', 'x86_64-unknown-linux-gnu'],
        cwd=os.path.join(ROOT, 'src-tauri')))
    nodes = {n['id']: n for n in meta['resolve']['nodes']}
    by_id = {p['id']: p for p in meta['packages']}
    seen, todo = set(), [meta['resolve']['root']]
    while todo:  # normal (shipped) dependencies only: no build or dev tools
        for dep in nodes[todo.pop()]['deps']:
            if any(k['kind'] is None for k in dep['dep_kinds']) and dep['pkg'] not in seen:
                seen.add(dep['pkg'])
                todo.append(dep['pkg'])
    for pid in seen:
        p = by_id[pid]
        yield p['name'], p['version'], p.get('license') or 'UNKNOWN', os.path.dirname(p['manifest_path'])

def build():
    head = ['Kinora third-party notices', '', 'Generated by scripts/third-party-notices.py. Licence of each package as it declares it, then its licence files.', '']
    index, missing = [], []
    shared = {}  # the same licence text is printed once, under every package that ships it
    for group, items in (('JavaScript packages', npm_packages()), ('Rust crates', cargo_packages())):
        items = sorted(items)
        index += [group, '-' * len(group)] + [f'{n} {v}: {l}' for n, v, l, _ in items] + ['']
        for n, v, l, folder in items:
            found = texts(folder) if os.path.isdir(folder) else []
            if not found:
                missing.append(f'{n} {v}')
            for _, text in found:
                shared.setdefault(text, []).append(f'{n} {v}')
    if missing:
        index += ['Packages that ship no licence file (their declared licence applies)', '-' * 66] + missing + ['']
    bodies = []
    for text, owners in shared.items():
        bodies += ['=' * 72, ', '.join(owners), '=' * 72, text, '']
    return '\n'.join(head + index + bodies) + '\n'

text = build()
if '--check' in sys.argv:
    if not os.path.exists(OUT) or open(OUT, encoding='utf-8').read() != text:
        sys.exit('public/THIRD-PARTY-NOTICES.txt is out of date: run python3 scripts/third-party-notices.py')
else:
    with open(OUT, 'w', encoding='utf-8') as f:
        f.write(text)
    print(f'{OUT}: {len(text) // 1024} KB')
